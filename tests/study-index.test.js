const { test } = require("node:test");
const assert = require("node:assert/strict");
const fs = require("node:fs/promises");
const os = require("node:os");
const path = require("node:path");
const { StudyBridgeDatabase } = require("../lib/database");
const { createStudyIndex } = require("../lib/study-index");
test("persistent bilingual per-question indexes isolate sources, invalidate revisions and bound recent-fragment memory", async (t) => {
  const directory = await fs.mkdtemp(path.join(os.tmpdir(), "studybridge-index-")); t.after(() => fs.rm(directory, { recursive: true, force: true }));
  const db = new StudyBridgeDatabase(); db.dynamo = null; db.local.file = path.join(directory, "db.json");
  const index = createStudyIndex({ db, maxCacheBytes: 10000 });
  const a = { id: "a", name: "Lecture.pdf", text: "background ".repeat(8000) + "Opportunity cost is the value of the best alternative forgone. A_ONLY", sourcePages: [] };
  const b = { id: "b", name: "Lecture.pdf", text: "Opportunity cost: B_ONLY", sourcePages: [] };
  const found = await index.retrieve("alice", "math", [a], "放弃其他选择的代价", ["opportunity cost"]);
  assert.ok(found.some((chunk) => chunk.text.includes("A_ONLY")));
  assert.ok((await index.retrieve("alice", "stats", [b], "opportunity cost")).every((chunk) => !chunk.text.includes("A_ONLY")));
  const restarted = createStudyIndex({ db, maxCacheBytes: 10000 });
  assert.ok((await restarted.retrieve("alice", "math", [a], "opportunity cost")).some((chunk) => chunk.text.includes("A_ONLY")));
  const changed = { ...a, text: "Price elasticity UPDATED_ONLY" };
  assert.ok((await index.retrieve("alice", "math", [changed], "elasticity")).some((chunk) => chunk.text.includes("UPDATED_ONLY")));
  for (let n = 0; n < 10; n++) await index.retrieve("alice", "math", [a], `opportunity cost ${n}`);
  assert.ok(index.cacheSize() <= 10000);
  index.invalidate("alice", "math"); assert.equal(index.cacheSize(), 0);
  await index.prepare("alice", "math", { id: "prototype", name: "__proto__", text: "constructor __proto__" });
});
test("a five-question batch loads each of seven persisted source indexes once", async (t) => {
  const directory = await fs.mkdtemp(path.join(os.tmpdir(), "studybridge-index-batch-")); t.after(() => fs.rm(directory, { recursive: true, force: true }));
  const db = new StudyBridgeDatabase(); db.dynamo = null; db.local.file = path.join(directory, "db.json");
  const index = createStudyIndex({ db }), sources = Array.from({ length: 7 }, (_, n) => ({ id: `source-${n}`, name: `Lecture ${n}`, text: "Opportunity cost is the best alternative forgone.\n".repeat(1000) }));
  for (const source of sources) await index.prepare("alice", "math", source);
  const read = db.readMaterial.bind(db); let reads = 0;
  db.readMaterial = (...args) => { if (args[2].startsWith("STUDYINDEX#")) reads++; return read(...args); };
  const questions = Array.from({ length: 5 }, (_, n) => ({ id: `q${n}`, text: `Explain opportunity cost ${n}`, queries: ["opportunity cost", "机会成本"] }));
  const evidence = await index.retrieveBatch("alice", "math", sources, questions);
  assert.equal(reads, 7); assert.equal(Object.keys(evidence).length, 5);
  assert.ok(Object.values(evidence).every((items) => items.length > 0 && items.length <= 4));
  const supplied = JSON.stringify(evidence).length, full = sources.reduce((sum, source) => sum + source.text.length, 0) * questions.length;
  assert.ok(supplied < full / 5, "Per-question context sends selected fragments rather than the full seven sources repeatedly");
});
