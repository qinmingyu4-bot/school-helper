const { test } = require("node:test");
const assert = require("node:assert/strict");
const fs = require("node:fs/promises");
const os = require("node:os");
const path = require("node:path");
const { spawn } = require("node:child_process");
const { once } = require("node:events");
const importer = require("../public/schedule-import");

test("timetable images/PDFs retain layout, use school calendars and return recurring drafts without saving reminders", { timeout: 30000 }, async (context) => {
  const root = path.resolve(__dirname, "..");
  const directory = await fs.mkdtemp(path.join(os.tmpdir(), "studybridge-timetable-"));
  const child = spawn(process.execPath, ["--require", "./tests/fixtures/echo-ai.js", "server.js"], { cwd: root, env: {
    ...process.env, PORT: "0", NODE_ENV: "test", STUDYBRIDGE_DB: "local", LOCAL_DB_FILE: path.join(directory, "db.json"), LOCAL_DB_BACKUP_DISABLED: "true",
    REQUIRE_INVITE_CODE: "false", REQUIRE_EMAIL_VERIFICATION: "false", OPENAI_API_KEY: "test-fixture", OPENAI_WEB_SEARCH: "true", SESSION_SECRET: "timetable-test-session"
  }, stdio: ["ignore", "pipe", "pipe"] });
  context.after(async () => { if (child.exitCode === null) { const stopped = once(child, "exit"); child.kill(); await stopped; } await fs.rm(directory, { recursive: true, force: true }); });
  const base = await new Promise((resolve, reject) => {
    let output = "";
    const timer = setTimeout(() => reject(new Error("Startup timed out")), 10000);
    child.once("error", (error) => { clearTimeout(timer); reject(error); });
    child.stdout.on("data", (chunk) => { output += chunk; const match = output.match(/http:\/\/localhost:(\d+)/); if (match) { clearTimeout(timer); resolve(`http://127.0.0.1:${match[1]}`); } });
  });
  async function request(route, body, cookie = "", method = "POST") {
    const response = await fetch(base + route, { method, headers: { "content-type": "application/json", cookie }, ...(body ? { body: JSON.stringify(body) } : {}) });
    return { status: response.status, cookie: response.headers.get("set-cookie")?.split(";")[0], data: await response.json() };
  }
  const account = await request("/api/auth/register", { name: "Timetable test", email: "timetable@example.test", password: "TimetableTest2026!", passwordConfirm: "TimetableTest2026!" });
  const cookie = account.cookie;
  assert.equal((await request("/api/me/profile", { name: "Timetable test", school: "University of Toronto" }, cookie, "PUT")).status, 200);
  const png = "iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+aOZkAAAAASUVORK5CYII=";
  const imageFile = { fileName: "weekly-timetable-fixture.png", fileData: `data:image/png;base64,${png}`, timeZone: "Asia/Shanghai" };
  assert.equal((await request("/api/schedule/extract", imageFile)).status, 401);
  const image = await request("/api/schedule/extract", imageFile, cookie);
  assert.equal(image.status, 200, JSON.stringify(image.data));
  assert.equal(image.data.items.length, 1);
  assert.equal(image.data.items[0].weekly.startTime, "10:00");
  assert.equal(image.data.items[0].warning, "");
  assert.equal(image.data.calendar.timeZone, "America/Toronto");
  assert.equal(image.data.calendar.teachingPeriods[0].endDate, "2026-12-07");
  const expanded = importer.expandWeekly(image.data.items, image.data.calendar, { fromDate: "2026-10-26" });
  assert.equal(expanded.length, 6);
  assert.equal(expanded[0].startsAt, "2026-11-02T10:00");
  const pdfBytes = await fs.readFile(path.join(root, "tests/fixtures/schedule-full.pdf"));
  const pdf = await request("/api/schedule/extract", { fileName: "weekly-timetable-fixture.pdf", fileData: pdfBytes.toString("base64"), timeZone: "America/Toronto" }, cookie);
  assert.equal(pdf.status, 200);
  assert.equal(pdf.data.items[0].weekly.endTime, "11:00");
  const autoCourses = (await request("/api/courses", null, cookie, "GET")).data.courses;
  assert.equal(autoCourses.length, 1);
  assert.equal(autoCourses[0].name, "FOR200H1");
  assert.equal(image.data.createdCourses.length, 1);
  assert.equal(pdf.data.createdCourses.length, 0, "PDF extraction reuses the course created from the image");
  assert.deepEqual((await request(`/api/courses/${autoCourses[0].id}/documents`, null, cookie, "GET")).data.documents, []);
  const unknownDay = await request("/api/schedule/extract", { fileName: "weekly-missing-day-fixture.txt", fileData: Buffer.from("Weekly timetable; weekday heading unreadable").toString("base64") }, cookie);
  assert.deepEqual(unknownDay.data.items[0].weekly.weekdays, []);
  assert.match(unknownDay.data.items[0].warning, /星期/);
  await request("/api/me/profile", { name: "Timetable test", school: "Unlisted test school" }, cookie, "PUT");
  const unknownSchool = await request("/api/schedule/extract", imageFile, cookie);
  assert.equal(unknownSchool.status, 200);
  assert.equal(unknownSchool.data.calendar, null);
  assert.ok(unknownSchool.data.items[0].weekly);
  assert.match(unknownSchool.data.calendarNotice, /一次/);
  const planner = (await request("/api/courses", { name: "Schedule & Deadlines" }, cookie)).data.course;
  const lecture = { kind: "LEC", title: "MAT101H1F LEC0101", course: "MAT101H1F", startsAt: "2026-11-02T15:00:00.000Z", endsAt: "2026-11-02T16:00:00.000Z", completedAt: "2026-11-02T16:00:00Z" };
  await request(`/api/courses/${planner.id}/documents`, { title: `[SCHEDULE_ITEM] ${lecture.title}`, type: "Schedule", text: JSON.stringify(lecture) }, cookie);
  const syllabusFile = { fileName: "syllabus-assessments-fixture.txt", fileData: Buffer.from("Course outline with lecture, Quiz 1, midterm and Assignment 1").toString("base64"), timeZone: "America/Toronto" };
  const syllabus = await request("/api/schedule/extract", syllabusFile, cookie);
  assert.equal(syllabus.status, 200, JSON.stringify(syllabus.data));
  assert.equal(syllabus.data.courses[0].name, "MAT101H1");
  assert.equal(syllabus.data.createdCourses.length, 1);
  const subject = syllabus.data.courses[0];
  assert.equal(syllabus.data.duplicateCount, 1);
  assert.deepEqual(syllabus.data.items.filter((item) => item.selected).map((item) => item.title), ["Quiz 1", "Midterm exam", "Assignment 1"]);
  assert.ok(syllabus.data.items.filter((item) => item.selected).every((item) => item.kind === "DDL"));
  assert.ok(syllabus.data.items.every((item) => item.timeZone === "America/Toronto"));
  const beforeConfirm = (await request(`/api/courses/${planner.id}/documents`, null, cookie, "GET")).data.documents;
  assert.equal(beforeConfirm.length, 1);
  assert.equal(beforeConfirm[0].text, JSON.stringify(lecture));
  const confirmed = await request("/api/schedule/import", { items: syllabus.data.items, source: syllabusFile.fileName, timeZone: "America/Toronto" }, cookie);
  assert.equal(confirmed.status, 200);
  assert.equal(confirmed.data.saved, 3);
  assert.ok(confirmed.data.items.every((item) => item.courseId === subject.id));
  assert.equal((await request(`/api/courses/${subject.id}/documents`, null, cookie, "GET")).data.documents.length, 3);
  const repeated = await request("/api/schedule/extract", syllabusFile, cookie);
  assert.equal(repeated.data.duplicateCount, 4);
  assert.equal(repeated.data.items.length, 4);
  assert.ok(repeated.data.items.every((item) => !item.selected && item.duplicateReview.duplicate));
  assert.equal(repeated.data.courses[0].id, subject.id);
  assert.deepEqual(repeated.data.createdCourses, []);
  assert.equal((await request(`/api/courses/${planner.id}/documents`, null, cookie, "GET")).data.documents.length, 1, "legacy planner entries remain unchanged");
  const other = await request("/api/auth/register", { name: "Other student", email: "other-timetable@example.test", password: "TimetableTest2026!", passwordConfirm: "TimetableTest2026!" });
  const isolated = await request("/api/schedule/extract", syllabusFile, other.cookie);
  assert.equal(isolated.data.duplicateCount, 0);
  assert.equal(isolated.data.items.length, 4);
  assert.equal(isolated.data.courses[0].name, "MAT101H1");
  assert.notEqual(isolated.data.courses[0].id, subject.id);
  const natural = { text: "明天下午三点到四点在图书馆复习，晚上八点交 STA437 作业", selectedDate: "2026-12-01", timeZone: "America/Toronto" };
  assert.equal((await request("/api/schedule/parse-text", natural)).status, 401);
  const plans = await request("/api/schedule/parse-text", natural, cookie);
  assert.equal(plans.status, 200, JSON.stringify(plans.data));
  assert.deepEqual(plans.data.items.map((item) => item.kind), ["EVENT", "DDL"]);
  assert.match(plans.data.items[0].endsAt, /T16:00$/);
  assert.equal(plans.data.items[0].timeZone, "America/Toronto");
  const missing = await request("/api/schedule/parse-text", { ...natural, text: "明天复习，没说时间" }, cookie);
  assert.equal(missing.data.items[0].startsAt, "");
  assert.ok(missing.data.items[0].warning);
  const repeat = await request("/api/schedule/parse-text", { ...natural, text: "每周一三点读书" }, cookie);
  assert.equal(repeat.data.items.length, 0); assert.match(repeat.data.clarification, /结束日期/);
  assert.equal((await request("/api/schedule/parse-text", { ...natural, text: "FORMAT_BAD" }, cookie)).status, 502);
  assert.equal((await request("/api/schedule/parse-text", { ...natural, timeZone: "bad/zone" }, cookie)).status, 400);
  const audio = { fileData: Buffer.from("524946461400000057415645666d742000000000", "hex").toString("base64") };
  assert.equal((await request("/api/schedule/transcribe", audio)).status, 401);
  const transcript = await request("/api/schedule/transcribe", audio, cookie);
  assert.equal(transcript.status, 200); assert.match(transcript.data.text, /图书馆/);
  assert.equal((await request("/api/schedule/transcribe", { fileData: "not audio" }, cookie)).status, 400);
  assert.equal((await request(`/api/courses/${planner.id}/documents`, null, cookie, "GET")).data.documents.length, 1);
  for (const item of plans.data.items) await request(`/api/courses/${planner.id}/documents`, { title: `[SCHEDULE_ITEM] ${item.title}`, type: "Schedule", text: JSON.stringify({ ...item, startsAt: importer.toUtc(item.startsAt, item.timeZone) }) }, cookie);
  const repeatedPlans = await request("/api/schedule/parse-text", natural, cookie);
  assert.equal(repeatedPlans.data.items.length, 2);
  assert.ok(repeatedPlans.data.items.every((item) => !item.selected));
  assert.equal(repeatedPlans.data.duplicateCount, 2);
  const portfolio = await request("/api/schedule/extract", { fileName: "portfolio-date-only-fixture.txt", fileData: Buffer.from("Portfolios are due on April 9, 2027. Late portfolios will not be accepted after April 14, 2027.").toString("base64"), timeZone: "America/Toronto" }, cookie);
  assert.equal(portfolio.status, 200);
  assert.equal(portfolio.data.items[0].date, "2027-04-09");
  assert.equal(portfolio.data.items[0].startsAt, "");
  assert.equal((await request("/api/schedule/import", { items: portfolio.data.items, timeZone: "America/Toronto" }, cookie)).status, 400, "a known date must not fabricate an exact deadline time");
  const filled = importer.withDatePart(portfolio.data.items[0], "time", "17:00");
  const added = await request("/api/schedule/import", { items: [filled], timeZone: "America/Toronto" }, cookie);
  assert.equal(added.data.saved, 1);
  assert.equal((await request("/api/schedule/import", { items: [filled], timeZone: "America/Toronto" }, cookie)).data.duplicates, 1);
  for (const order of [["timetable", "syllabus"], ["syllabus", "timetable"]]) {
    const testCookie = (await request("/api/auth/register", { name: "No calendar test", email: `no-calendar-${order[0]}@example.test`, password: "NoCalendar-Test-2026!", passwordConfirm: "NoCalendar-Test-2026!" })).cookie;
    const file = (type) => ({ fileName: `weekly-no-calendar-fixture-${type}.txt`, fileData: Buffer.from("QA801H1 Monday 10:00 to 11:00, November 2 to November 9 2026").toString("base64"), timeZone: "America/Toronto" });
    const first = await request("/api/schedule/extract", file(order[0]), testCookie);
    assert.equal(first.status, 200);
    assert.equal(first.data.calendar, null);
    const moduleCalendar = { timeZone: "America/Toronto", teachingPeriods: [{ startDate: "2026-11-02", endDate: "2026-11-09" }], breaks: [] };
    const meetings = importer.expandWeekly(first.data.items, moduleCalendar);
    assert.equal((await request("/api/schedule/import", { items: meetings, timeZone: "America/Toronto" }, testCookie)).data.saved, 2);
    const second = await request("/api/schedule/extract", file(order[1]), testCookie);
    assert.equal(second.status, 200);
    assert.equal(second.data.calendar, null);
    assert.equal(second.data.items[0].selected, false, order.join(" then "));
    assert.equal(second.data.items[0].duplicateReview.existingCount, 2);
    assert.match(importer.duplicateNotice(second.data.items[0]), /日历中已有/);
    assert.equal((await request("/api/schedule/import", { items: meetings, timeZone: "America/Toronto" }, testCookie)).data.saved, 0);
  }

});
